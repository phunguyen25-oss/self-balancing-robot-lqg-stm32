/**
 * @file    config.h
 * @brief   Single source of truth for the 2-wheel self-balancing robot
 *          firmware: LQG matrices, mechanical/physical placeholders, pin
 *          map, and every safety/saturation/ramp limit.
 *
 * WHAT IS "REAL" vs "PLACEHOLDER" IN THIS FILE
 * ---------------------------------------------
 * - AD/BD/CD/KD/LD below were computed from the doc's ILLUSTRATIVE physical
 *   parameters (M=0.2kg, m=0.8kg, l=0.10m, I=0.005 kg*m^2, b=0.02 N*s/m),
 *   independently re-derived and verified with tools/lqg_design.py (see
 *   that file's header comment). They are internally self-consistent
 *   (Ad-Bd*Kd and Ad-Ld*Cd are both verified Schur-stable) but they are
 *   NOT your robot's real gains yet.
 * - WHEEL_RADIUS_M / MOTOR_STEPS_PER_REV / MICROSTEPPING / GEAR_RATIO are
 *   placeholders -- fill in with your actual hardware.
 *
 * WORKFLOW TO GO FROM PLACEHOLDER TO REAL:
 *   1. Measure M, m, l, I, b on your actual robot (see README.md).
 *   2. Edit tools/lqg_design.py with those numbers, run it.
 *   3. Copy/paste the printed AD/BD/CD/KD/LD arrays over the ones below.
 *   4. Measure/set WHEEL_RADIUS_M, MOTOR_STEPS_PER_REV, MICROSTEPPING,
 *      GEAR_RATIO to match your mechanics.
 *   Nothing else in the firmware needs to change.
 */
