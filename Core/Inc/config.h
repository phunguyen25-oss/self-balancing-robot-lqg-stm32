/* =========================================================================
 * 14) PIN / PERIPHERAL MAP -- STM32F103C8T6 "Blue Pill"
 *     This is the authoritative pin table; CubeMX must be configured to
 *     match it exactly (see README.md "CubeMX configuration" for the
 *     click-by-click peripheral setup).
 * ========================================================================= *
 *  I2C1  SCL=PB6, SDA=PB7   : MPU6050 (0x68) + AS5600 #1 (0x36) share this
 *                              bus -- different addresses, no conflict.
 *  I2C2  SCL=PB10, SDA=PB11 : AS5600 #2 (0x36) alone -- needs its OWN bus
 *                              because the AS5600 address is fixed in
 *                              silicon (can't have two 0x36 on one bus).
 *  TIM2  (no pins)          : basic timer, 5 ms update interrupt, drives
 *                              the whole control ISR (HAL_TIM_PeriodElapsedCallback).
 *  TIM3  CH1 = PA6          : STEP pulses, LEFT wheel (PWM freq = step rate,
 *                              ~50% duty, frequency set by writing ARR/PSC
 *                              each control cycle).
 *  TIM4  CH3 = PB8          : STEP pulses, RIGHT wheel (same scheme; CH3
 *                              chosen, not CH1=PB6, to avoid colliding
 *                              with I2C1 above).
 *  GPIO out, push-pull:
 *     DIR_L      = PA4   DIR_R      = PA5
 *     EN_L       = PA7   EN_R       = PB9   (DRV8825 ENABLE is ACTIVE-LOW:
 *                                             drive low to enable the driver)
 *     STATUS_LED = PC13  (onboard LED on most Blue Pill boards, active-low)
 *     FAULT_LED  = PB13  (external LED, optional but recommended)
 *  GPIO in, pull-up, active-low:
 *     MODE_BTN   = PB12  (present per BOM; NOT wired into a state machine
 *                          in this core-only build -- reserved for a
 *                          future mode switch / manual recalibrate trigger)
 *  Reserved, do not repurpose:
 *     PA9/PA10 (USART1)  -- reserved for the HC-05 Bluetooth module (BOM),
 *                            unused by this core-only firmware.
 *     PA13/PA14          -- SWD debug (SWDIO/SWCLK), leave free.
 *     PA11/PA12          -- USB D-/D+, leave free even if unused.
 *     PB2                -- BOOT1 strap pin, avoid using as GPIO.
 */

